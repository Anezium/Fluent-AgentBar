    // The OpenAI, Cursor and Grok marks are monochrome by design and follow the
    // host theme; Claude and Gemini keep their brand colour.
    internal static string PathDataFor(string? providerName)
    {
        return AppConfigStore.NormalizeProvider(providerName) switch
        {
            "claude" => ClaudePathData,
            "gemini" => GeminiPathData,
            "cursor" => CursorPathData,
            "grok" => GrokPathData,
            _ => OpenAiPathData
        };
    }

    internal static Geometry GeometryFor(string providerName)
    {
        return (Geometry)XamlBindingHelper.ConvertValue(typeof(Geometry), PathDataFor(providerName));
    }

    // The source marks use a 256x256 viewBox; PathIcon and other fixed-size
    // hosts need the geometry pre-scaled to their viewport.
    internal static Geometry IconGeometryFor(string providerName, double size)
    {
        Geometry geometry = GeometryFor(providerName);
        double scale = size / 256.0;
        geometry.Transform = new ScaleTransform { ScaleX = scale, ScaleY = scale };
        return geometry;
    }

    internal static Brush BrushForTheme(string providerName, ElementTheme theme)
    {
        return BrandColorFor(providerName) is Color brand
            ? new SolidColorBrush(brand)
            : new SolidColorBrush(MonochromeColor(theme == ElementTheme.Dark));
    }

    internal static Brush BrushFor(string providerName)
    {
        return BrandColorFor(providerName) is Color brand
            ? new SolidColorBrush(brand)
            : new SolidColorBrush(MonochromeColor(TaskbarTheme.IsDark()));
    }

    private static Color? BrandColorFor(string? providerName)
    {
        return AppConfigStore.NormalizeProvider(providerName) switch
        {
            "claude" => ClaudeBrandColor,
            "gemini" => GeminiBrandColor,
            _ => null
        };
    }

    private static Color MonochromeColor(bool dark)
    {
        return dark
            ? Color.FromArgb(255, 255, 255, 255)
            : Color.FromArgb(228, 0, 0, 0);
    }
